// Pure routing and conditional-flow logic of the manage-agents-router plugin, installed next to routing.json.
//
// Supports both simple trigger -> subagent model tables (`routes`) and rich IF/OR conditional rules (`rules`) over:
//   - callers in OR (`archetype.callers`, or rule-specific `rule.callers`)
//   - triggers in OR (`*`, `provider`, or `provider/model`; exact model > provider > `*`)
//   - `then.models`      subagent model routing (`inherit` or `provider/model[#variant]`, skipping pinned subagents)
//   - `then.tools`       `allow` | `ask` | `deny` over exact tools or `<prefix>_*` / `*` families
//   - `then.permissions` `allow` | `ask` | `deny` over permission actions
//   - `then.delegations` `allow` | `deny` over delegated subagent IDs or `*`
//
// routing.json is generated by `manage-agents reconcile` from pack defaults and user settings; never edit by hand.

export const ROUTING_VERSION = 2
export const SUBAGENT_TOOLS = new Set(["subagent", "task"])
const MODEL_RE = /^[^\s/#]+\/[^\s#]+(?:#[^\s#]+)?$/
const TRIGGER_RE = /^(?:\*|(?!\$)[^\s/#]+(?:\/[^\s#]+)?)$/
const RESOURCE_KEY_RE = /^[^\s]+$/
const POLICY_EFFECTS = new Set(["allow", "ask", "deny"])
const DELEGATION_EFFECTS = new Set(["allow", "deny"])
const RULE_KEYS = new Set(["callers", "triggers", "then", "layer"])
const POLICY_KEYS = new Set(["models", "tools", "permissions", "delegations"])

export const isModelRef = (value) => typeof value === "string" && MODEL_RE.test(value)

const setOwn = (object, key, value) =>
  Object.defineProperty(object, key, { value, enumerable: true, writable: true, configurable: true })
const own = (object, key) => (object && Object.hasOwn(object, key) ? object[key] : undefined)
const isPlain = (value) => typeof value === "object" && value !== null && !Array.isArray(value)
const isList = (value) => Array.isArray(value) && value.every(item => typeof item === "string" && item.length > 0)

/** { provider, model, full } from a hook payload ({providerID, id|modelID, variant}) or a "provider/model#variant" string. */
export function modelOf(ref) {
  if (typeof ref === "string") {
    if (!isModelRef(ref)) return null
    const [base] = ref.split("#")
    const slash = base.indexOf("/")
    return { provider: base.slice(0, slash), model: base.slice(slash + 1), full: ref }
  }
  if (!ref || typeof ref !== "object") return null
  const provider = ref.providerID ?? ref.provider
  const model = ref.id ?? ref.modelID ?? ref.model
  if (typeof provider !== "string" || !provider || typeof model !== "string" || !model) return null
  const variant = typeof ref.variant === "string" && ref.variant ? `#${ref.variant}` : ""
  return { provider, model, full: `${provider}/${model}${variant}` }
}

function validateRule(rule, where, fail) {
  if (!isPlain(rule)) fail(`${where}: rule must be an object`)
  for (const key of Object.keys(rule)) if (!RULE_KEYS.has(key)) fail(`${where}: unknown key '${key}'`)
  if (rule.callers !== undefined && (!isList(rule.callers) || rule.callers.length === 0)) {
    fail(`${where}: callers must be a non-empty list of agent IDs`)
  }
  if (!isList(rule.triggers) || rule.triggers.length === 0 || !rule.triggers.every(trigger => TRIGGER_RE.test(trigger))) {
    fail(`${where}: triggers must be a non-empty list of valid triggers`)
  }
  if (rule.layer !== undefined && rule.layer !== 0 && rule.layer !== 1 && rule.layer !== 2) {
    fail(`${where}: invalid layer '${rule.layer}'`)
  }
  if (!isPlain(rule.then)) fail(`${where}: missing then`)
  for (const key of Object.keys(rule.then)) if (!POLICY_KEYS.has(key)) fail(`${where}.then: unknown key '${key}'`)
  if (rule.then.models !== undefined) {
    if (!isPlain(rule.then.models)) fail(`${where}.then.models: not an object`)
    for (const [agent, model] of Object.entries(rule.then.models)) {
      if (!RESOURCE_KEY_RE.test(agent) || (model !== "inherit" && !isModelRef(model))) {
        fail(`${where}.then.models.${agent}: '${model}' is not "inherit" or provider/model[#variant]`)
      }
    }
  }
  for (const field of ["tools", "permissions"]) {
    const map = rule.then[field]
    if (map === undefined) continue
    if (!isPlain(map)) fail(`${where}.then.${field}: not an object`)
    for (const [name, effect] of Object.entries(map)) {
      if (!RESOURCE_KEY_RE.test(name) || !POLICY_EFFECTS.has(effect)) fail(`${where}.then.${field}.${name}: invalid effect '${effect}'`)
    }
  }
  if (rule.then.delegations !== undefined) {
    if (!isPlain(rule.then.delegations)) fail(`${where}.then.delegations: not an object`)
    for (const [name, effect] of Object.entries(rule.then.delegations)) {
      if (!RESOURCE_KEY_RE.test(name) || !DELEGATION_EFFECTS.has(effect)) fail(`${where}.then.delegations.${name}: invalid effect '${effect}'`)
    }
  }
}

/** Returns the routing or throws with the first problem. Accepts runtime versions 2 and 3. */
export function validateRouting(value) {
  const fail = (message) => { throw new Error(`routing.json: ${message}`) }
  if (!isPlain(value)) fail("not an object")
  if (value.version !== ROUTING_VERSION && value.version !== 3) fail(`unsupported version ${value.version}`)
  if (!isPlain(value.archetypes)) fail("missing archetypes")
  for (const [id, archetype] of Object.entries(value.archetypes)) {
    if (!isList(archetype?.callers)) fail(`${id}: callers must be a list of agent IDs`)
    if (!isList(archetype.pinned)) fail(`${id}: pinned must be a list of agent IDs`)
    if (!isPlain(archetype.routes)) fail(`${id}: missing routes`)
    for (const [trigger, agents] of Object.entries(archetype.routes)) {
      if (!TRIGGER_RE.test(trigger)) fail(`${id}: invalid trigger '${trigger}'`)
      if (!isPlain(agents)) fail(`${id}.${trigger}: not an object`)
      for (const [agent, model] of Object.entries(agents)) {
        if (model !== "inherit" && !isModelRef(model)) fail(`${id}.${trigger}.${agent}: '${model}' is not "inherit" or provider/model[#variant]`)
      }
    }
    if (archetype.rules !== undefined) {
      if (!Array.isArray(archetype.rules)) fail(`${id}.rules: must be an array`)
      archetype.rules.forEach((rule, index) => validateRule(rule, `${id}.rules[${index}]`, fail))
    }
  }
  return value
}

/** Specificity of a rule's OR trigger list against `parsedModel`: 2 = exact model, 1 = provider, 0 = "*", -1 = no match. */
export function matchTriggerSpecificity(triggers, parsedModel) {
  if (!Array.isArray(triggers)) return -1
  if (parsedModel && triggers.includes(`${parsedModel.provider}/${parsedModel.model}`)) return 2
  if (parsedModel && triggers.includes(parsedModel.provider)) return 1
  if (triggers.includes("*")) return 0
  return -1
}

/** Matches `name` against a policy map: exact key first, then longest `<prefix>*` pattern, then `*`. */
export function matchPolicyMap(map, name) {
  if (!isPlain(map) || typeof name !== "string" || !name) return null
  if (Object.hasOwn(map, name)) return map[name]
  let bestPrefixLen = -1
  let bestEffect = null
  for (const key of Object.keys(map)) {
    if (key === "*" || !key.endsWith("*")) continue
    const prefix = key.slice(0, -1)
    if (name.startsWith(prefix) && prefix.length > bestPrefixLen) {
      bestPrefixLen = prefix.length
      bestEffect = map[key]
    }
  }
  if (bestEffect !== null) return bestEffect
  return Object.hasOwn(map, "*") ? map["*"] : null
}

/** The archetype whose callers (or rule callers) include this agent, or null. */
export function archetypeOf(routing, agent) {
  if (typeof agent !== "string") return null
  return Object.values(routing?.archetypes ?? {}).find(archetype =>
    archetype.callers.includes(agent) ||
    (Array.isArray(archetype.rules) && archetype.rules.some(rule => Array.isArray(rule.callers) && rule.callers.includes(agent))),
  ) ?? null
}

/** The routes for the caller's model: exact "provider/model" first, then "provider", then "*". */
export function routeFor(archetype, callerModel) {
  const model = modelOf(callerModel)
  const merged = {}
  const layers = [
    own(archetype?.routes, "*"),
    model ? own(archetype?.routes, model.provider) : undefined,
    model ? own(archetype?.routes, `${model.provider}/${model.model}`) : undefined,
  ].filter(Boolean)
  if (!layers.length) return null
  for (const layer of layers) {
    for (const [agent, target] of Object.entries(layer)) setOwn(merged, agent, target)
  }
  return merged
}

/** Effective merged policy `{ archetype, models, tools, permissions, delegations }` for `(callerAgent, callerModel)`. */
export function resolveEffectivePolicy(routing, { callerAgent, callerModel }) {
  if (!routing || typeof callerAgent !== "string" || !callerAgent) return null
  const archetype = archetypeOf(routing, callerAgent)
  if (!archetype) return null
  const parsedModel = modelOf(callerModel)
  const models = {}
  const tools = {}
  const permissions = {}
  const delegations = {}

  if (archetype.callers.includes(callerAgent)) {
    const baseRoute = routeFor(archetype, callerModel)
    if (baseRoute) for (const [agent, target] of Object.entries(baseRoute)) setOwn(models, agent, target)
  }

  const matchedRules = (archetype.rules ?? [])
    .map((rule, index) => {
      const ruleCallers = rule.callers ?? archetype.callers
      if (!ruleCallers.includes(callerAgent)) return null
      const specificity = matchTriggerSpecificity(rule.triggers, parsedModel)
      if (specificity < 0) return null
      return { rule, layer: rule.layer ?? 0, specificity, index }
    })
    .filter(Boolean)
    .sort((a, b) => a.layer - b.layer || a.specificity - b.specificity || a.index - b.index)

  for (const { rule } of matchedRules) {
    for (const [k, v] of Object.entries(rule.then.models ?? {})) setOwn(models, k, v)
    for (const [k, v] of Object.entries(rule.then.tools ?? {})) setOwn(tools, k, v)
    for (const [k, v] of Object.entries(rule.then.permissions ?? {})) setOwn(permissions, k, v)
    for (const [k, v] of Object.entries(rule.then.delegations ?? {})) setOwn(delegations, k, v)
  }

  return { archetype, models, tools, permissions, delegations, parsedModel }
}

/** { model } to inject into a subagent call, or null to leave the call as it is. */
export function decideSubagentModel(routing, { callerAgent, callerModel, targetAgent, requestedModel }) {
  if (!routing || (typeof requestedModel === "string" && requestedModel.trim())) return null
  if (typeof targetAgent !== "string" || !targetAgent) return null
  const policy = resolveEffectivePolicy(routing, { callerAgent, callerModel })
  if (!policy || policy.archetype.pinned.includes(targetAgent)) return null
  const model = own(policy.models, targetAgent)
  if (!isModelRef(model) || model === policy.parsedModel?.full) return null
  return { model }
}

function isToolDeniedByPermissions(permissions, toolName) {
  if (!isPlain(permissions) || typeof toolName !== "string") return false
  if (matchPolicyMap(permissions, toolName) === "deny") return true
  if (toolName === "bash" && matchPolicyMap(permissions, "shell") === "deny") return true
  if (toolName === "shell" && matchPolicyMap(permissions, "bash") === "deny") return true
  if (toolName === "write" && matchPolicyMap(permissions, "edit") === "deny") return true
  return false
}

/** Tool names to remove from `event.tools` in `session.hook("context")` for `(agent, model)`. */
export function decideSessionTools(routing, { agent, model, toolNames }) {
  if (!routing || !Array.isArray(toolNames) || !toolNames.length) return []
  const policy = resolveEffectivePolicy(routing, { callerAgent: agent, callerModel: model })
  if (!policy) return []
  const allDelegationsDenied =
    own(policy.delegations, "*") === "deny" && !Object.values(policy.delegations).some(effect => effect === "allow")
  return toolNames.filter(name => {
    if (matchPolicyMap(policy.tools, name) === "deny") return true
    if (isToolDeniedByPermissions(policy.permissions, name)) return true
    if (allDelegationsDenied && SUBAGENT_TOOLS.has(name)) return true
    return false
  })
}

/** `{ effect, message? }` override for `permission.hook("evaluate")`, or null when no conditional rule applies. */
export function decidePermission(routing, { agent, model, action }) {
  if (!routing || typeof action !== "string" || !action) return null
  const policy = resolveEffectivePolicy(routing, { callerAgent: agent, callerModel: model })
  if (!policy) return null
  const altAction = action === "shell" ? "bash" : action === "bash" ? "shell" : null
  const effect =
    matchPolicyMap(policy.permissions, action) ??
    (altAction ? matchPolicyMap(policy.permissions, altAction) : null) ??
    matchPolicyMap(policy.tools, action) ??
    (altAction ? matchPolicyMap(policy.tools, altAction) : null)
  if (!effect) return null
  const modelLabel = policy.parsedModel ? `${policy.parsedModel.provider}/${policy.parsedModel.model}` : "the active model"
  return {
    effect,
    ...(effect !== "allow" ? { message: `Conditional flow (${agent} on ${modelLabel}) sets "${action}" to ${effect}.` } : {}),
  }
}

/** Inspects a tool call in `tool.hook("execute.before")`: blocks denied tools/delegations and routes subagent models. */
export function decideToolExecution(routing, { callerAgent, callerModel, tool, input }) {
  if (!routing || typeof tool !== "string" || !tool) return null
  const policy = resolveEffectivePolicy(routing, { callerAgent, callerModel })
  if (!policy) return null
  const modelLabel = policy.parsedModel ? `${policy.parsedModel.provider}/${policy.parsedModel.model}` : "the active model"
  if (matchPolicyMap(policy.tools, tool) === "deny" || isToolDeniedByPermissions(policy.permissions, tool)) {
    return { blocked: true, reason: `Tool "${tool}" is disabled by manage-agents conditional flow when ${callerAgent} runs on ${modelLabel}.` }
  }
  if (!SUBAGENT_TOOLS.has(tool) || !isPlain(input)) return null
  const targetAgent = input.agent ?? input.subagent_type
  if (typeof targetAgent === "string" && targetAgent && matchPolicyMap(policy.delegations, targetAgent) === "deny") {
    return { blocked: true, reason: `Delegation to "${targetAgent}" is disabled by manage-agents conditional flow when ${callerAgent} runs on ${modelLabel}.` }
  }
  const modelDecision = decideSubagentModel(routing, {
    callerAgent,
    callerModel,
    targetAgent,
    requestedModel: input.model,
  })
  return modelDecision ? { blocked: false, model: modelDecision.model } : null
}
